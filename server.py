class DatabaseConnection:
    def __init__(self, connection, postgres=False, pooled=False):
        self.manager = connection
        self.connection = connection
        self.postgres = postgres
        self.pooled = pooled

    def __enter__(self):
        if self.pooled:
            self.connection = self.manager.__enter__()
        else:
            self.connection.__enter__()
        return self

    def __exit__(self, exception_type, exception, traceback):
        return self.manager.__exit__(exception_type, exception, traceback)

    def execute(self, statement, parameters=()):
        if self.postgres:
            statement = statement.replace("?", "%s")
        return self.connection.execute(statement, parameters)

    def executescript(self, script):
        if not self.postgres:
            return self.connection.executescript(script)
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)


def connect_db():
    if DATABASE_URL:
        if psycopg is None or ConnectionPool is None:
            raise RuntimeError("ثبّت حزم psycopg وpsycopg-pool لتوصيل قاعدة PostgreSQL")
        global DATABASE_POOL
        if DATABASE_POOL is None:
            DATABASE_POOL = ConnectionPool(
                DATABASE_URL,
                min_size=0,
                max_size=1,
                kwargs={"row_factory": dict_row, "prepare_threshold": None, "sslmode": "require"},
                open=True,
            )
        return DatabaseConnection(DATABASE_POOL.connection(), postgres=True, pooled=True)
    connection = sqlite3.connect(DB_PATH, timeout=15)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA journal_mode = WAL")
    return DatabaseConnection(connection)


