def hash_password(password, salt=None):
    salt_bytes = bytes.fromhex(salt) if salt else secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt_bytes, 310_000)
    return digest.hex(), salt_bytes.hex()


def store_product_image(image_name, image_bytes, mime):
    if SUPABASE_URL:
        if not SUPABASE_SERVICE_ROLE_KEY:
            raise RuntimeError("لم يتم إعداد مفتاح تخزين الصور في الخادم")
        bucket = quote(SUPABASE_STORAGE_BUCKET, safe="")
        object_name = quote(image_name, safe="")
        endpoint = f"{SUPABASE_URL}/storage/v1/object/{bucket}/{object_name}"
        request = urllib.request.Request(
            endpoint,
            data=image_bytes,
            headers={
                "apikey": SUPABASE_SERVICE_ROLE_KEY,
                "Authorization": f"Bearer {SUPABASE_SERVICE_ROLE_KEY}",
                "Content-Type": mime,
                "x-upsert": "true",
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(request, timeout=30):
                pass
        except urllib.error.URLError as error:
            sys.stderr.write(f"Supabase image upload failed: {error}\n")
            raise ValueError("تعذر حفظ صورة المنتج")
        return f"{SUPABASE_URL}/storage/v1/object/public/{bucket}/{object_name}"
    if DATABASE_URL:
        raise RuntimeError("أعد إعداد SUPABASE_URL لتخزين صور المنتجات خارج الخادم")
    (UPLOAD_DIR / image_name).write_bytes(image_bytes)
    return f"/uploads/{image_name}"


