def setting(db, key, default=""):
    row = db.execute("SELECT value FROM settings WHERE key = ?", (key,)).fetchone()
    return row["value"] if row else default


class StoreHandler(BaseHTTPRequestHandler):
    server_version = "GroceryStore/1.0"

    def log_message(self, format_string, *args):
        sys.stdout.write("%s - %s\n" % (self.address_string(), format_string % args))

    def send_json(self, status, payload, headers=None):
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        if headers:
            for key, value in headers.items():
                self.send_header(key, value)
        self.end_headers()
        self.wfile.write(body)

    def send_file(self, path, content_type=None):
        try:
            body = path.read_bytes()
        except OSError:
            self.send_error(404)
            return
        self.send_response(200)
        self.send_header("Content-Type", content_type or mimetypes.guess_type(path.name)[0] or "application/octet-stream")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(body)

    def read_json(self):
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            raise ValueError("حجم الطلب غير صحيح")
        if length < 1 or length > MAX_BODY:
            raise ValueError("حجم البيانات غير مسموح")
        try:
            value = json.loads(self.rfile.read(length).decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            raise ValueError("تعذر قراءة البيانات")
        if not isinstance(value, dict):
            raise ValueError("صيغة البيانات غير صحيحة")
        return value

    def verify_origin(self):
        origin = self.headers.get("Origin")
        if origin and urlparse(origin).netloc != self.headers.get("Host"):
            self.send_json(403, {"error": "الطلب غير مسموح"})
            return False
        return True

    def current_session(self, role):
        cookie_name = SESSION_COOKIE_NAMES[role]
        cookie = self.headers.get("Cookie", "")
        token = ""
        for part in cookie.split(";"):
            key, separator, value = part.strip().partition("=")
            if separator and key == cookie_name:
                token = value
                break
        if not token:
            return None
        token_hash = hashlib.sha256(token.encode("ascii", errors="ignore")).hexdigest()
        with connect_db() as db:
            row = db.execute(
                "SELECT s.role, s.admin_name, u.id, u.name, u.email, u.phone "
                "FROM sessions s LEFT JOIN users u ON u.id = s.user_id "
                "WHERE s.token_hash = ? AND s.expires_at > ?",
                (token_hash, int(time.time())),
            ).fetchone()
        if not row or row["role"] != role:
            return None
        if row["role"] == "admin":
            return {"role": "admin", "name": row["admin_name"] or "الإدارة"}
        return {"role": "customer", "id": row["id"], "name": row["name"], "email": row["email"], "phone": row["phone"]}

    def require_role(self, role):
        session = self.current_session(role)
        if not session or session["role"] != role:
            self.send_json(401, {"error": "يلزم تسجيل الدخول أولاً"})
            return None
        return session

    def create_session(self, role, user_id=None, admin_name=None):
        token = secrets.token_urlsafe(32)
        token_hash = hashlib.sha256(token.encode("ascii")).hexdigest()
        expires_at = int(time.time()) + SESSION_DAYS * 86400
        with connect_db() as db:
            db.execute(
                "INSERT INTO sessions (token_hash, role, user_id, admin_name, expires_at) VALUES (?, ?, ?, ?, ?)",
                (token_hash, role, user_id, admin_name, expires_at),
            )
        secure = "; Secure" if os.environ.get("HTTPS", "").lower() in {"1", "true", "yes"} else ""
        cookie_name = SESSION_COOKIE_NAMES[role]
        return {"Set-Cookie": f"{cookie_name}={token}; Path=/; HttpOnly; SameSite=Lax; Max-Age={SESSION_DAYS * 86400}{secure}"}

    def do_GET(self):
        path = unquote(urlparse(self.path).path)
        if path in {"/", "/auth", "/admin"}:
            self.send_file(ROOT / "index.html", "text/html; charset=utf-8")
            return
        if path == "/static/app.js":
            self.send_file(ROOT / "app.js", "text/javascript; charset=utf-8")
            return
        if path == "/static/styles.css":
            self.send_file(ROOT / "styles.css", "text/css; charset=utf-8")
            return
        if path.startswith("/uploads/"):
            name = Path(path).name
            if name != path.removeprefix("/uploads/") or not re.fullmatch(r"[a-f0-9]{32}\.(jpg|png|webp)", name):
                self.send_error(404)
                return
            self.send_file(UPLOAD_DIR / name)
            return
        if not path.startswith("/api/"):
            self.send_error(404)
            return
        if path == "/api/session":
            role = parse_qs(urlparse(self.path).query).get("role", ["customer"])[0]
            if role not in SESSION_COOKIE_NAMES:
                role = "customer"
            session = self.current_session(role)
            with connect_db() as db:
                store = {"name": setting(db, "store_name", "بقالة الحي")}
            self.send_json(200, {"user": session, "store": store})
            return
        if path == "/api/products":
            with connect_db() as db:
                rows = db.execute("SELECT * FROM products WHERE visible = 1 AND stock > 0 ORDER BY category, name").fetchall()
                store = {"name": setting(db, "store_name", "بقالة الحي"), "whatsapp": setting(db, "whatsapp_phone")}
            self.send_json(200, {"products": [safe_product(row) for row in rows], "store": store})
            return
        if path == "/api/admin/products":
            if not self.require_role("admin"):
                return
            with connect_db() as db:
                rows = db.execute("SELECT * FROM products ORDER BY updated_at DESC, id DESC").fetchall()
            self.send_json(200, {"products": [safe_product(row) for row in rows]})
            return
        if path == "/api/admin/settings":
            if not self.require_role("admin"):
                return
            with connect_db() as db:
                settings = {"name": setting(db, "store_name", "بقالة الحي"), "whatsapp": setting(db, "whatsapp_phone")}
            self.send_json(200, {"settings": settings})
            return
        if path == "/api/admin/orders":
            if not self.require_role("admin"):
                return
            with connect_db() as db:
                rows = db.execute("SELECT * FROM orders ORDER BY created_at DESC LIMIT 100").fetchall()
            orders = []
            for row in rows:
                orders.append({
                    "id": row["id"], "customerName": row["customer_name"], "phone": row["customer_phone"],
                    "city": row["city"], "district": row["district"], "street": row["street"], "house": row["house"],
                    "note": row["note"], "items": json.loads(row["items_json"]), "total": row["total"],
                    "latitude": row["latitude"], "longitude": row["longitude"],
                    "status": row["status"], "createdAt": row["created_at"],
                })
            self.send_json(200, {"orders": orders})
            return
        self.send_json(404, {"error": "المسار غير موجود"})

    def do_POST(self):
        if not self.verify_origin():
            return
        path = unquote(urlparse(self.path).path)
        try:
            data = self.read_json()
            if path == "/api/auth/register":
                return self.register(data)
            if path == "/api/auth/login":
                return self.login(data)
            if path == "/api/admin/login":
                return self.admin_login(data)
            if path == "/api/logout":
                return self.logout(data)
            if path == "/api/orders":
                return self.create_order(data)
            if path == "/api/assistant":
                return self.assistant(data)
            if path == "/api/admin/products":
                return self.save_product(data)
        except ValueError as error:
            self.send_json(400, {"error": str(error)})
        except DB_INTEGRITY_ERRORS:
            self.send_json(409, {"error": "البريد الإلكتروني مستخدم بالفعل"})
        except Exception as error:
            sys.stderr.write(f"Request error: {error}\n")
            self.send_json(500, {"error": "حدث خطأ في الخادم"})

    def do_PUT(self):
        if not self.verify_origin():
            return
        path = unquote(urlparse(self.path).path)
        try:
            data = self.read_json()
            match = re.fullmatch(r"/api/admin/products/(\d+)", path)
            if match:
                return self.save_product(data, int(match.group(1)))
            if path == "/api/admin/settings":
                return self.save_settings(data)
            match = re.fullmatch(r"/api/admin/orders/([a-f0-9-]+)/status", path)
            if match:
                return self.update_order_status(data, match.group(1))
            self.send_json(404, {"error": "المسار غير موجود"})
        except ValueError as error:
            self.send_json(400, {"error": str(error)})
        except Exception as error:
            sys.stderr.write(f"Request error: {error}\n")
            self.send_json(500, {"error": "حدث خطأ في الخادم"})

    def do_DELETE(self):
        if not self.verify_origin():
            return
        path = unquote(urlparse(self.path).path)
        match = re.fullmatch(r"/api/admin/products/(\d+)", path)
        if not match:
            self.send_json(404, {"error": "المسار غير موجود"})
            return
        if not self.require_role("admin"):
            return
        with connect_db() as db:
            db.execute("DELETE FROM products WHERE id = ?", (int(match.group(1)),))
        self.send_json(200, {"ok": True})

    def register(self, data):
        name = str(data.get("name", "")).strip()[:80]
        email = str(data.get("email", "")).strip().lower()[:254]
        phone = re.sub(r"\D", "", str(data.get("phone", "")))[:16]
        password = str(data.get("password", ""))
        if len(name) < 2 or not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
            raise ValueError("أدخل الاسم والبريد الإلكتروني بشكل صحيح")
        if not re.fullmatch(r"[0-9]{8,16}", phone):
            raise ValueError("أدخل رقم جوال صحيحاً مع رمز الدولة")
        if len(password) < 8 or len(password) > 128:
            raise ValueError("كلمة المرور يجب أن تكون 8 أحرف على الأقل")
        password_hash, salt = hash_password(password)
        with connect_db() as db:
            if db.execute("SELECT 1 FROM users WHERE REPLACE(phone, '+', '') = ?", (phone,)).fetchone():
                raise ValueError("رقم الجوال مستخدم بالفعل")
            cursor = db.execute(
                "INSERT INTO users (name, email, phone, password_hash, password_salt, created_at) VALUES (?, ?, ?, ?, ?, ?) RETURNING id",
                (name, email, phone, password_hash, salt, int(time.time())),
            )
            user_id = cursor.fetchone()["id"]
        headers = self.create_session("customer", user_id=user_id)
        self.send_json(201, {"user": {"id": user_id, "role": "customer", "name": name, "email": email, "phone": phone}}, headers)

    def login(self, data):
        identifier = str(data.get("identifier", data.get("email", ""))).strip()
        password = str(data.get("password", ""))
        with connect_db() as db:
            if "@" in identifier:
                row = db.execute("SELECT * FROM users WHERE email = ?", (identifier.lower(),)).fetchone()
            else:
                phone = re.sub(r"\D", "", identifier)
                row = db.execute("SELECT * FROM users WHERE REPLACE(phone, '+', '') = ? LIMIT 1", (phone,)).fetchone()
        if not row:
            hash_password(password, "00" * 16)
            self.send_json(401, {"error": "البريد أو كلمة المرور غير صحيحة"})
            return
        candidate, _ = hash_password(password, row["password_salt"])
        if not hmac.compare_digest(candidate, row["password_hash"]):
            self.send_json(401, {"error": "البريد أو كلمة المرور غير صحيحة"})
            return
        headers = self.create_session("customer", user_id=row["id"])
        self.send_json(200, {"user": {"id": row["id"], "role": "customer", "name": row["name"], "email": row["email"], "phone": row["phone"]}}, headers)

    def admin_login(self, data):
        expected_user = os.environ.get("ADMIN_USERNAME", "admin")
        expected_password = os.environ.get("STORE_ADMIN_PASSWORD", "")
        supplied_user = str(data.get("username", ""))
        supplied_password = str(data.get("password", ""))
        if not expected_password:
            self.send_json(503, {"error": "لم يتم إعداد كلمة مرور الإدارة على الخادم"})
            return
        valid = hmac.compare_digest(supplied_user, expected_user) and hmac.compare_digest(supplied_password, expected_password)
        if not valid:
            self.send_json(401, {"error": "بيانات دخول الإدارة غير صحيحة"})
            return
        headers = self.create_session("admin", admin_name="مدير المتجر")
        self.send_json(200, {"user": {"role": "admin", "name": "مدير المتجر"}}, headers)

    def logout(self, data):
        role = data.get("role")
        if role not in SESSION_COOKIE_NAMES:
            raise ValueError("نوع الحساب غير صالح")
        cookie_name = SESSION_COOKIE_NAMES[role]
        cookie = self.headers.get("Cookie", "")
        token = ""
        for part in cookie.split(";"):
            key, separator, value = part.strip().partition("=")
            if separator and key == cookie_name:
                token = value
                break
        if token:
            token_hash = hashlib.sha256(token.encode("ascii", errors="ignore")).hexdigest()
            with connect_db() as db:
                db.execute("DELETE FROM sessions WHERE token_hash = ?", (token_hash,))
        self.send_json(200, {"ok": True}, {"Set-Cookie": f"{cookie_name}=; Path=/; HttpOnly; SameSite=Lax; Max-Age=0"})

    def save_product(self, data, product_id=None):
        if not self.require_role("admin"):
            return
        name = str(data.get("name", "")).strip()[:120]
        description = str(data.get("description", "")).strip()[:500]
        category = str(data.get("category", "")).strip()[:60]
        try:
            price = round(float(data.get("price")), 2)
            stock = int(data.get("stock"))
        except (TypeError, ValueError):
            raise ValueError("تحقق من السعر والكمية")
        visible = 1 if data.get("visible", True) else 0
        if not name or not category or not math.isfinite(price) or price <= 0 or price > 1_000_000 or stock < 0 or stock > 1_000_000:
            raise ValueError("أدخل اسماً وقسماً وسعراً وكمية صحيحة")
        image = str(data.get("image", ""))
        if image.startswith("data:"):
            match = re.fullmatch(r"data:image/(jpeg|png|webp);base64,([A-Za-z0-9+/=]+)", image)
            if not match:
                raise ValueError("صيغة الصورة غير مدعومة")
            mime = match.group(1)
            try:
                image_bytes = base64.b64decode(match.group(2), validate=True)
            except ValueError:
                raise ValueError("تعذر قراءة الصورة")
            if len(image_bytes) > 5 * 1024 * 1024:
                raise ValueError("حجم الصورة يجب أن يكون أقل من 5 ميغابايت")
            extension = {"jpeg": "jpg", "png": "png", "webp": "webp"}[mime]
            image_name = f"{uuid.uuid4().hex}.{extension}"
            image = store_product_image(image_name, image_bytes, f"image/{mime}")
        elif image and not re.fullmatch(r"/uploads/[a-f0-9]{32}\.(jpg|png|webp)", image) and not image.startswith(f"{SUPABASE_URL}/storage/v1/object/public/{SUPABASE_STORAGE_BUCKET}/"):
            raise ValueError("مسار الصورة غير صالح")
        with connect_db() as db:
            if product_id:
                old = db.execute("SELECT * FROM products WHERE id = ?", (product_id,)).fetchone()
                if not old:
                    self.send_json(404, {"error": "المنتج غير موجود"})
                    return
                if not image:
                    image = old["image"]
                db.execute(
                    "UPDATE products SET name=?, description=?, category=?, price=?, stock=?, image=?, visible=?, updated_at=? WHERE id=?",
                    (name, description, category, price, stock, image, visible, int(time.time()), product_id),
                )
                saved_id = product_id
            else:
                cursor = db.execute(
                    "INSERT INTO products (name, description, category, price, stock, image, visible, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?) RETURNING id",
                    (name, description, category, price, stock, image, visible, int(time.time())),
                )
                saved_id = cursor.fetchone()["id"]
            row = db.execute("SELECT * FROM products WHERE id = ?", (saved_id,)).fetchone()
        self.send_json(200, {"product": safe_product(row)})

    def save_settings(self, data):
        if not self.require_role("admin"):
            return
        name = str(data.get("name", "")).strip()[:80]
        phone = re.sub(r"[^0-9]", "", str(data.get("whatsapp", "")))[:16]
        if len(name) < 2:
            raise ValueError("اسم المتجر مطلوب")
        if phone and not re.fullmatch(r"[1-9][0-9]{7,15}", phone):
            raise ValueError("أدخل رقم واتساب بصيغة دولية دون علامة +")
        with connect_db() as db:
            db.execute("INSERT INTO settings (key, value) VALUES ('store_name', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (name,))
            db.execute("INSERT INTO settings (key, value) VALUES ('whatsapp_phone', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (phone,))
        self.send_json(200, {"settings": {"name": name, "whatsapp": phone}})

    def create_order(self, data):
        user = self.require_role("customer")
        if not user:
            return
        address = data.get("address", {})
        city = str(address.get("city", "")).strip()[:80]
        district = str(address.get("district", "")).strip()[:80]
        street = str(address.get("street", "")).strip()[:120]
        house = str(address.get("house", "")).strip()[:40]
        note = str(address.get("note", "")).strip()[:300]
        latitude = longitude = None
        latitude_value = str(address.get("latitude", "")).strip()
        longitude_value = str(address.get("longitude", "")).strip()
        if bool(latitude_value) != bool(longitude_value):
            raise ValueError("تعذر حفظ الموقع المحدد")
        if latitude_value:
            try:
                latitude = float(latitude_value)
                longitude = float(longitude_value)
            except ValueError:
                raise ValueError("إحداثيات الموقع غير صحيحة")
            if not math.isfinite(latitude) or not math.isfinite(longitude) or not -90 <= latitude <= 90 or not -180 <= longitude <= 180:
                raise ValueError("إحداثيات الموقع غير صحيحة")
        requested = data.get("items", [])
        if not all((city, district, street, house)):
            raise ValueError("أكمل المدينة والحي والشارع ورقم المنزل")
        if not isinstance(requested, list) or not requested or len(requested) > 60:
            raise ValueError("السلة فارغة أو غير صالحة")
        with connect_db() as db:
            user_row = db.execute("SELECT name, phone FROM users WHERE id = ?", (user["id"],)).fetchone()
            quantities = {}
            for requested_item in requested:
                try:
                    product_id = int(requested_item["id"])
                    quantity = int(requested_item["quantity"])
                except (KeyError, TypeError, ValueError):
                    raise ValueError("عنصر غير صالح في السلة")
                if quantity < 1 or quantity > 99:
                    raise ValueError("كمية المنتج غير صالحة")
                quantities[product_id] = quantities.get(product_id, 0) + quantity
            items = []
            total = 0
            for product_id, quantity in quantities.items():
                if quantity > 99:
                    raise ValueError("كمية المنتج غير صالحة")
                product = db.execute("SELECT id, name, price, stock, visible FROM products WHERE id = ?", (product_id,)).fetchone()
                if not product or not product["visible"] or product["stock"] < quantity:
                    raise ValueError("أحد المنتجات لم يعد متوفراً بالكمية المطلوبة")
                line_total = round(product["price"] * quantity, 2)
                total = round(total + line_total, 2)
                items.append({"id": product_id, "name": product["name"], "price": product["price"], "quantity": quantity, "subtotal": line_total})
                db.execute("UPDATE products SET stock = stock - ?, updated_at = ? WHERE id = ?", (quantity, int(time.time()), product_id))
            order_id = uuid.uuid4().hex[:12]
            db.execute(
                "INSERT INTO orders (id, user_id, customer_name, customer_phone, city, district, street, house, note, items_json, total, status, created_at, latitude, longitude) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'new', ?, ?, ?)",
                (order_id, user["id"], user_row["name"], user_row["phone"], city, district, street, house, note, json.dumps(items, ensure_ascii=False), total, int(time.time()), latitude, longitude),
            )
            whatsapp = setting(db, "whatsapp_phone")
        self.send_json(201, {"order": {"id": order_id, "total": total, "items": items, "latitude": latitude, "longitude": longitude}, "whatsapp": whatsapp})

    def update_order_status(self, data, order_id):
        if not self.require_role("admin"):
            return
        status = str(data.get("status", ""))
        if status not in {"new", "preparing", "on_way", "complete", "cancelled"}:
            raise ValueError("حالة الطلب غير صالحة")
        with connect_db() as db:
            order = db.execute("SELECT status, items_json FROM orders WHERE id = ?", (order_id,)).fetchone()
            if not order:
                self.send_json(404, {"error": "الطلب غير موجود"})
                return
            if order["status"] == "cancelled" and status != "cancelled":
                raise ValueError("لا يمكن إعادة فتح طلب ملغي")
            if status == "cancelled" and order["status"] != "cancelled":
                for item in json.loads(order["items_json"]):
                    db.execute("UPDATE products SET stock = stock + ?, updated_at = ? WHERE id = ?", (item["quantity"], int(time.time()), item["id"]))
            db.execute("UPDATE orders SET status = ? WHERE id = ?", (status, order_id))
        self.send_json(200, {"ok": True})

    def assistant(self, data):
        if not self.require_role("customer"):
            return
        question = str(data.get("message", "")).strip()[:500]
        if not question:
            raise ValueError("اكتب سؤالك أولاً")
        with connect_db() as db:
            rows = db.execute("SELECT name, category, price, stock FROM products WHERE visible = 1 AND stock > 0 ORDER BY category, name LIMIT 100").fetchall()
        product_lines = [f"{row['name']} | {row['category']} | {row['price']:.2f} SAR | available: {row['stock']}" for row in rows]
        api_key = os.environ.get("AI_API_KEY", "")
        if api_key:
            endpoint = os.environ.get("AI_API_URL", "https://api.openai.com/v1/chat/completions")
            model = os.environ.get("AI_MODEL", "gpt-4o-mini")
            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": "You are a concise, helpful grocery shopping assistant. Reply in the customer's language. Recommend only items found in this live catalog, mention prices in SAR, and never claim an unavailable item is in stock. Catalog:\n" + "\n".join(product_lines)},
                    {"role": "user", "content": question},
                ],
                "temperature": 0.4,
                "max_tokens": 350,
            }
            request = urllib.request.Request(endpoint, data=json.dumps(payload).encode("utf-8"), headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}, method="POST")
            try:
                with urllib.request.urlopen(request, timeout=12) as response:
                    result = json.loads(response.read().decode("utf-8"))
                answer = result["choices"][0]["message"]["content"].strip()
                self.send_json(200, {"answer": answer, "mode": "ai"})
                return
            except (urllib.error.URLError, TimeoutError, KeyError, IndexError, json.JSONDecodeError) as error:
                sys.stderr.write(f"Assistant provider error: {error}\n")
        terms = [term.lower() for term in re.findall(r"\w+", question, flags=re.UNICODE) if len(term) > 2]
        matches = [row for row in rows if any(term in row["name"].lower() or term in row["category"].lower() for term in terms)]
        if matches:
            answer = "وجدت لك هذه الخيارات المتوفرة: " + "، ".join(f"{row['name']} بسعر {row['price']:.2f} ر.س" for row in matches[:5]) + "."
        elif rows:
            answer = "أستطيع مساعدتك باقتراح المنتجات المتوفرة. الأقسام الحالية تشمل: " + "، ".join(sorted({row["category"] for row in rows})) + "."
        else:
            answer = "لم يضف المتجر منتجات متاحة بعد. يمكنك العودة لاحقاً أو التواصل مع المتجر مباشرة."
        self.send_json(200, {"answer": answer, "mode": "catalog"})


def run_local_server():
    initialize_db()
    host = os.environ.get("HOST", "0.0.0.0")
    port = int(os.environ.get("PORT", "8000"))
    server = ThreadingHTTPServer((host, port), StoreHandler)
    server.daemon_threads = True
    print(f"Grocery store running at http://{host}:{port}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    run_local_server()
